export const PROJECT_BY_ID: ReadonlyMap<string, RealEstateProject> = new Map(
  PROJECTS.map((project) => [project.id, project]),
);

export const PROJECT_TO_GOV_MAP: ReadonlyMap<string, ActiveGovernorateId> = new Map(
  PROJECTS.map((project) => [project.id, project.governorateId]),
);

export function getProjectById(id: string | null | undefined): RealEstateProject | undefined {
  if (!id) return undefined;
  return PROJECT_BY_ID.get(id);
}

export function getProjectsByGovernorate(
  governorateId: ActiveGovernorateId,
): RealEstateProject[] {
  return PROJECTS.filter((project) => project.governorateId === governorateId);
}

export function getUniqueDevelopers(
  projects: readonly RealEstateProject[] = PROJECTS,
): Array<{ ar: string; en: string }> {
  const seen = new Map<string, { ar: string; en: string }>();
  for (const project of projects) {
    if (!seen.has(project.developer.en)) {
      seen.set(project.developer.en, { ...project.developer });
    }
  }
  return Array.from(seen.values());
}
